/**
 * @brief Test group for gdb_point debugging utility functionality
 *
 * This test group verifies the functionality of the gdb_point debugging utility,
 * which is used for debug-printing behavior. The group redirects std::cout to an
 * internal stringstream so that tests can inspect any output generated by gdb_point.
 */
TEST_GROUP(GdbPointTests)
{
	// Test fixtures
	std::streambuf* old_cout_buffer;
	std::stringstream test_cout_buffer;

	/**
	 * @brief Set up test fixtures before each test
	 *
	 * Saves the current std::cout buffer and redirects std::cout to the internal
	 * stringstream so that any output from gdb_point can be captured and inspected.
	 */
	void setup()
	{
		// Save and redirect cout
		old_cout_buffer = std::cout.rdbuf();
		std::cout.rdbuf(test_cout_buffer.rdbuf());
	}

	/**
	 * @brief Clean up test fixtures after each test
	 *
	 * Restores std::cout to its original buffer and clears the internal capture
	 * buffer so that output from different test cases does not interfere.
	 */
	void teardown()
	{
		// Restore cout
		std::cout.rdbuf(old_cout_buffer);
		// Clean the buffer for the next test
		test_cout_buffer.str("");
		// Clear any mock expectations
		mock_c()->clear();
	}
};
/**
 * @brief TC_001: Verify gdb_point returns immediately when debug flag is 0
 *
 * This test verifies that when bdebug is 0, gdb_point does not print anything
 * to std::cout and returns immediately, leaving the captured output buffer empty.
 */
TEST(GdbPointTests, TC_001_ReturnImmediatelyWhenDebugFlagIsZero)
{
	// ARRANGE: Set debug flag to 0
	uint8_t bdebug = 0;

	// ACT: Call the function under test
	gdb_point(bdebug);

	// ASSERT: Verify no output was generated
	STRCMP_EQUAL("", test_cout_buffer.str().c_str());
}
